# Retrocue and encoding stay repulsive at every level, so they get a tighter
# axis than the two distance sweeps, which cross into attraction.
REPULSION_YLIM = (0, 45)
REPULSION_YTICKS = (0, 15, 30, 45)
# The readout the bias experiments actually use (Supplementary S1.5).
LOC_POOL_W = 60.0
BASELINE_FRAC = 0.8
# The drawn display puts the two items one slot apart, which fixes the
# neighbour's surround gain rather than leaving it a free knob.
ITEM_DLOC = 45.0
NEIGHBOUR_GAIN = float(np.exp(-0.5 * (ITEM_DLOC / LOC_POOL_W) ** 2))
ICON_RING_R = 0.345

_C = np.linspace(-180.0, 180.0, 721, endpoint=False)


def _bump(mu, width):
    d = (_C - mu + 180.0) % 360.0 - 180.0
    return np.exp(-0.5 * (d / width) ** 2)


def blending_force(dc, slice_width=55.0, leak=0.70,
                   neighbour_gain=NEIGHBOUR_GAIN):
    """Close items: the prior merges them, then the same pool readout as
    S1.5 is applied. The merge still wins, so the peak sits between them."""
    target = _bump(0.0, slice_width)
    neighbour = _bump(dc, slice_width)
    blended = target + leak * neighbour
    # The same leak at the neighbour's location pulls its profile back
    # toward the target, so the two peaks meet around the midpoint.
    neighbour_shifted = neighbour + leak * target
    pool = target + neighbour_gain * neighbour
    readout = blended / (BASELINE_FRAC * blended.max() + pool)
    return dict(dc=dc, target=target, neighbour=neighbour, blended=blended,
                neighbour_shifted=neighbour_shifted, pool=pool,
                readout=readout, peak=float(_C[int(np.argmax(readout))]))


def normalization_force(dc, slice_width=55.0, neighbour_gain=NEIGHBOUR_GAIN):
    """The readout acting alone: the pool is heavier on the neighbour's side,
    so dividing by it moves the peak the other way."""
    target = _bump(0.0, slice_width)
    neighbour = _bump(dc, slice_width)
    pool = target + neighbour_gain * neighbour
    readout = target / (BASELINE_FRAC * target.max() + pool)
    return dict(dc=dc, target=target, neighbour=neighbour, pool=pool,
                readout=readout, peak=float(_C[int(np.argmax(readout))]))


# Vertical layout of one mechanism sub-panel, in data units. Curves occupy
# 0..1; everything else is stacked around them.
_Y0, _Y1 = -1.20, 1.68
_STRIP = (-0.40, -0.25)
_MARK_Y = -0.325
_ITEM_Y = -0.47
_ARROW_Y = -0.80
_OUT_Y = -1.16
_FORCE_SHAFT = 24.0
_PEAK_Y = 1.06
_HEAD_Y = 1.60
_IN_AMP = 0.55  # single-item bumps, kept clear of the bold result at 1.0


# Both 4a sub-panels share this window so a degree of color is the same
# physical width on the left (close items) and the right (far items).
MECH_X0 = -106.0
MECH_X1 = 185.0


def _mech_axes(ax, header):
    """A bare canvas whose x axis is the color dimension itself."""
    ax.set_xlim(MECH_X0, MECH_X1)
    ax.set_ylim(_Y0, _Y1)
    ax.set_xticks([])
    ax.set_yticks([])
    for side in ("top", "right", "left", "bottom"):
        ax.spines[side].set_visible(False)
    ns.color_strip(ax, MECH_X0, MECH_X1, _STRIP[0], _STRIP[1], chroma=32.0)
    ax.text(MECH_X0, _HEAD_Y, header, ha="left", va="top", fontsize=FS_HEAD,
            fontweight="bold", color=INK)


def _mark_peak(ax, peak, colour):
    """Where the report lands. The probed color is marked only by its square."""
    dash = (0, (1.5, 2))
    ax.plot([peak, peak], [_STRIP[1], _PEAK_Y], color=colour, lw=0.7,
            ls=dash, zorder=2)
    ax.plot([peak], [_PEAK_Y], marker="v", ms=5.0, color=colour, zorder=6,
            markeredgecolor="white", markeredgewidth=0.6)
    ax.text(peak, _PEAK_Y + 0.08, "report", ha="center", va="bottom",
            fontsize=FS_MIN, color=colour)


def _items(ax, dc):
    """The two items as markers on the color axis; the probed one is ringed."""
    ax.plot([0], [_MARK_Y], marker="s", ms=7.4, color=ns.color_to_rgb(0.0),
            markeredgecolor=INK, markeredgewidth=1.3, zorder=6)
    ax.plot([dc], [_MARK_Y], marker="s", ms=6.0, color=ns.color_to_rgb(dc),
            markeredgecolor=ns.GREY_DK, markeredgewidth=0.8, zorder=6)
    ax.text(0, _ITEM_Y, "probed", ha="center", va="top", fontsize=FS_MIN,
            color=INK, fontweight="bold")
    ax.text(dc, _ITEM_Y, "neighbor", ha="center", va="top", fontsize=FS_MIN,
            color=ns.GREY_DK)


def _force(ax, kind, peak):
    """The probed item's report is displaced; the neighbor stays put."""
    if kind == "attract":
        x0, x1 = 0.0, _FORCE_SHAFT
        colour, label = TOWARD, "attraction"
    else:
        mid = 0.5 * peak
        x0, x1 = mid + 0.5 * _FORCE_SHAFT, mid - 0.5 * _FORCE_SHAFT
        colour, label = AWAY, "repulsion"
    ax.annotate("", xy=(x1, _ARROW_Y), xytext=(x0, _ARROW_Y),
                arrowprops=dict(arrowstyle="-|>", color=colour, lw=1.8,
                                mutation_scale=10, shrinkA=0, shrinkB=0),
                zorder=4)
    ax.text(0.5 * (x0 + x1), _OUT_Y, label, ha="center", va="bottom",
            fontsize=FS_NOTE, color=colour, fontweight="bold")


def _display_icon(ax, dc):
    """The display these curves come from: two items one slot apart in
    location, dc apart in color, with the probed one ringed."""
    icon = ax.inset_axes([0.66, 0.615, 0.34, 0.315])
    ns.blank(icon, equal=True)
    icon.set_anchor("E")
    icon.set_xlim(0, 1)
    icon.set_ylim(0, 1)
    ns.task_screen(icon, 0.5, 0.5, s=0.98, ec=ns.GREY_LT, lw=0.9,
                   fixation=False)
    # One slot apart in location puts the two squares at +-ITEM_DLOC/2 on the
    # ring, so their edge-to-edge gap is 2*r*sin(ITEM_DLOC/2) minus their half
    # widths. The ring has to be wide enough to leave that gap visible.
    ns.stim_items(icon, [(-ITEM_DLOC / 2, dc)], 0.5, 0.5, ring_r=ICON_RING_R,
                  sq=0.145, edge=ns.GREY, lw=0.8)
    ns.stim_items(icon, [(ITEM_DLOC / 2, 0.0)], 0.5, 0.5, ring_r=ICON_RING_R,
                  sq=0.190, edge=INK, lw=1.4, ghost_ring=False)


def _draw_pool(ax, pool):
    """The S1.5 normalization pool, drawn the same way on both sides."""
    y = 0.80 * pool / pool.max()
    ax.fill_between(_C, 0, y, color=ns.GREY_LT, alpha=1.0, lw=0, zorder=1)


def panel_blend(ax):
    """Close colors: generalization has already shifted the target profile.

    The pool is built from the same overlapping profiles, so it has nearly the
    same shape. Division leaves the peak where that shifted profile put it.
    """
    near = blending_force(dc=58.0)
    _mech_axes(ax, "Attraction")
    _draw_pool(ax, near["pool"])
    shifted = near["blended"]
    ax.plot(_C, _IN_AMP * shifted / shifted.max(), color=ns.GREY_DK, lw=0.9,
            ls=(0, (2.6, 2)), zorder=3)
    # Neighbour profile, shifted toward the target. The peaks sit far enough
    # apart that the two curves can share a height.
    neigh = near["neighbour_shifted"]
    ax.plot(_C, _IN_AMP * neigh / neigh.max(), color=GREY, lw=0.9,
            ls=(0, (1, 1.7)), zorder=3)
    ax.plot(_C, near["readout"] / near["readout"].max(), color=TOWARD, lw=2.2,
            zorder=5)
    _mark_peak(ax, near["peak"], TOWARD)
    _items(ax, near["dc"])
    _force(ax, "attract", near["peak"])
    _display_icon(ax, near["dc"])


def panel_divide(ax):
    """The readout alone: the pool leans toward the neighbour, pushing out."""
    far = normalization_force(dc=115.0)
    _mech_axes(ax, "Repulsion")
    _draw_pool(ax, far["pool"])
    ax.plot(_C, _IN_AMP * far["neighbour"], color=GREY, lw=0.9,
            ls=(0, (1, 1.7)), zorder=3)
    ax.plot(_C, _IN_AMP * far["target"], color=ns.GREY_DK, lw=0.9,
            ls=(0, (2.6, 2)), zorder=3)
    ax.plot(_C, far["readout"] / far["readout"].max(), color=AWAY, lw=2.2,
            zorder=5)
    _mark_peak(ax, far["peak"], AWAY)
    _items(ax, far["dc"])
    _force(ax, "repel", far["peak"])
    _display_icon(ax, far["dc"])


def _group(summary, family, levels):
    sub = summary[
        (summary["family"] == family)
        & summary["level"].isin(levels)
        & (summary["readout"] == "normalized")
    ].copy()
    return sub.set_index("level").loc[levels].reset_index()


def bias_axis(
    ax,
    sub,
    labels,
    title,
    xlabel,
    annotate=True,
    ylim=(-55, 55),
    yticks=(-50, -25, 0, 25, 50),
):
    x = np.arange(len(sub))
    # On a purely repulsive panel the zero line would sit on the bottom spine.
    signed = ylim[0] < 0
    if signed:
        ax.axhline(0, color=GREY, lw=0.7, ls=(0, (3, 2)), zorder=1)
    ax.errorbar(
        x,
        sub["bias_pct"],
        yerr=sub["bias_sem"],
        fmt="o-",
        color=BLUE,
        ecolor=GREY,
        capsize=2.5,
        lw=1.5,
        ms=4.6,
        mfc=BLUE,
        mec="white",
        mew=0.8,
        zorder=3,
    )
    if annotate and len(sub) <= 3:
        # Two-point panels put the marker on the axis edge, so the value has to
        # sit inward or it lands on the y tick labels.
        for i, (xi, yi) in enumerate(zip(x, sub["bias_pct"])):
            first = i == 0
            ax.text(
                xi + (0.08 if first else -0.08),
                yi + 9,
                f"{yi:+.1f}%",
                ha="left" if first else "right",
                va="center",
                fontsize=FS_MIN,
                color=BLUE,
            )
    ax.set_xticks(x, labels)
    ax.set_xlim(-0.42, len(sub) - 1 + 0.42)
    ax.set_ylim(*ylim)
    ax.set_yticks(list(yticks))
    ax.set_ylabel("bias (%)")
    ax.set_xlabel(xlabel, labelpad=2)
    ax.set_title(title, loc="left", fontsize=FS_HEAD, fontweight="bold", pad=2)
    ax.text(
        0.98,
        0.96,
        "repulsion",
        transform=ax.transAxes,
        ha="right",
        va="top",
        fontsize=FS_MIN,
        color=AWAY,
    )
    if signed:
        ax.text(
            0.98,
            0.04,
            "attraction",
            transform=ax.transAxes,
            ha="right",
            va="bottom",
            fontsize=FS_MIN,
            color=TOWARD,
        )


def hist_axis(ax, trials, family, levels, labels):
    bins = np.linspace(-180, 180, 37)
    # Background: negative oriented error = toward neighbor (attraction);
    # positive = away from neighbor (repulsion).
    ax.axvspan(-180, 0, facecolor=TOWARD, alpha=0.12, lw=0, ec="none", zorder=0)
    ax.axvspan(0, 180, facecolor=AWAY, alpha=0.12, lw=0, ec="none", zorder=0)
    peak = 0.0
    for level, color in zip(levels, PAIR):
        values = trials[
            (trials["family"] == family)
            & (trials["level"] == level)
            & (trials["readout"] == "normalized")
        ]["oriented_error_deg"].to_numpy()
        counts, _, _ = ax.hist(
            values,
            bins=bins,
            density=True,
            histtype="step",
            lw=1.25,
            color=color,
            zorder=2,
        )
        peak = max(peak, float(np.max(counts)))
    ax.axvline(0, color=GREY, lw=0.7, ls=(0, (3, 2)), zorder=1)
    ax.set_xlim(-180, 180)
    # Headroom for the labels above the tallest bar; the distributions are all
    # sharply peaked, so the space costs nothing legible.
    ax.set_ylim(0, peak * HIST_HEADROOM)
    ax.set_xticks([-180, -90, 0, 90, 180])
    ax.set_yticks([])
    ax.set_ylabel("density")
    ax.set_xlabel("oriented error (deg)")
    # Colouring the condition names instead of drawing a legend box keeps the
    # key narrow enough to sit beside the central peak rather than on it.
    for i, (label, color) in enumerate(zip(labels, PAIR)):
        ax.text(
            0.025,
            0.99 - 0.185 * i,
            label,
            transform=ax.transAxes,
            ha="left",
            va="top",
            fontsize=FS_LEG,
            fontweight="bold",
            color=color,
            zorder=3,
        )


def card(
    fig,
    spec,
    summary,
    trials,
    family,
    levels,
    labels,
    title,
    xlabel,
    hist_levels=None,
    hist_labels=None,
    annotate=True,
    ylim=(-55, 55),
    yticks=(-50, -25, 0, 25, 50),
):
    inner = spec.subgridspec(2, 1, height_ratios=[1.0, 0.72], hspace=0.62)
    ax_top = fig.add_subplot(inner[0])
    ax_hist = fig.add_subplot(inner[1])
    bias_axis(
        ax_top,
        _group(summary, family, levels),
        labels,
        title,
        xlabel,
        annotate=annotate,
        ylim=ylim,
        yticks=yticks,
    )
    hist_axis(
        ax_hist,
        trials,
        family,
        hist_levels or levels,
        hist_labels or labels,
    )
    return ax_top, ax_hist


def _human_precision_repulsion():
    """Chunharas et al. (2022) Exp. 4: subject-level circ-SD vs bias %.

    Aggregate over all encoding × color-distance cells (including distance 0),
    matching the subject means underlying their reported Pearson r = -.81.
    """
    raw = pd.read_csv(
        HUMAN_EXP4,
        header=None,
        names=["subject", "encoding_s", "color_distance", "val", "circ_sd"],
    )
    # CSV ``val`` is already P(away) - 0.5 (see Fig4c.m / R colnames).
    raw["bias_pct"] = 100.0 * raw["val"]
    sub = (
        raw.groupby("subject", as_index=False)
        .agg(circ_sd=("circ_sd", "mean"), bias_pct=("bias_pct", "mean"))
    )
    return sub


def _memgp_precision_repulsion():
    """Per simulated subject: circular SD and bias, averaged over distances.

    Matching the human Exp. 4 aggregation, each quantity is computed per
    color distance and then averaged over distances. Two bias measures:
      bias_pct  100 * P(report away from the distractor) - 50, all trials
      bias_deg  mean oriented error (positive = away), errors > 40 deg excluded
    """
    df = pd.read_csv(PERF_CSV)
    per_dist = df.groupby(["subject", "sigma", "distance"])[["error", "oriented_error"]].apply(
        lambda g: pd.Series({
            "circ_sd": ns.circ_sd_deg(g["error"].to_numpy(float)),
            "bias_pct": 100.0 * np.mean(g["oriented_error"] > 0) - 50.0,
            "bias_deg": g.loc[g["error"].abs() <= 40.0, "oriented_error"].mean(),
        })
    ).reset_index()
    return (per_dist.groupby(["subject", "sigma"], as_index=False)
            [["circ_sd", "bias_pct", "bias_deg"]].mean())


def memgp_bias_measure(memgp):
    """Fig. 4g uses the mean oriented error in degrees."""
    return "bias_deg", "repulsion bias (deg)"


def plot_precision_scatter(ax, x, y, *, color, ylabel, title, cvals=None):
    if cvals is not None:
        ax.scatter(
            x,
            y,
            c=cvals,
            cmap="viridis",
            s=28,
            edgecolor="white",
            linewidth=0.55,
            zorder=4,
        )
    else:
        ax.scatter(
            x,
            y,
            color=color,
            s=28,
            edgecolor="white",
            linewidth=0.55,
            alpha=0.9,
            zorder=4,
        )
    slope, intercept, r, p, _se = stats.linregress(x, y)
    xs = np.linspace(np.min(x), np.max(x), 50)
    ax.plot(xs, intercept + slope * xs, color=color, lw=1.4, ls=(0, (5, 2)),
            zorder=5)
    ax.axhline(0, color=GREY, lw=0.6, ls=(0, (3, 2)), zorder=1)
    ax.set_xlabel("circular SD (deg)")
    ax.set_ylabel(ylabel)
    ax.set_title(title, loc="left", fontsize=FS_HEAD, fontweight="bold", pad=2,
                 color=color)
    ax.text(
        0.96,
        0.95,
        f"r = {r:.2f}",
        transform=ax.transAxes,
        ha="right",
        va="top",
        fontsize=7.0,
        color=color,
    )
    return r, p


